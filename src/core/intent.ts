/**
 * 打たれた言葉が、作業の依頼か、ただの問いかけかを見分ける。
 *
 * **ここまで、打った言葉は全部「作業」として扱っていた。**
 * 役職は 12 人いて、どれも作業の役職。話し相手が一人もいない。
 * だから「明日の天気は？」にも、
 *
 *   あなたはソフトウェア開発の作業者です。与えられた作業ディレクトリで
 *   実際に手を動かします。守ること: 推測でファイルを書かない。まず
 *   read_file / list_files / search_text で現状を確認する。…
 *
 * という決まりと、リポジトリの決まりと、作業場の様子と、ツールの説明が載った。
 * 2B のモデルはその形に引きずられて、問いをなぞって「完了」と返す（実機）。
 * **模型が弱いのではなく、問いに作業の服を着せていた。**
 *
 * 見分けは**モデルに判じさせない**。同じ言葉で毎回同じ答えが要る。
 * 規則で見て、**迷ったら作業の側に倒す**（作業を問いと読むと手が止まるが、
 * 問いを作業と読んでも、答えが少し固くなるだけで済む）。
 */

/** 作業場のものを指していると分かる形。 */
const POINTS_AT_CODE = [
  /[./\\][a-z0-9_-]+\.[a-z0-9]{1,6}\b/i, // src/a.ts, ./x.json, foo.md
  /\b[a-z0-9_-]+\/[a-z0-9_-]+/i, // src/core, node_modules/…
  /```/, // 貼り付けたコード
  /\b(npm|node|git|pytest|cargo|docker|make)\b/i,
];

/** 手を動かせ、と言っている形。 */
const ASKS_FOR_WORK = [
  /直し|修正|なおして|直す/,
  /使って|呼んで|試して|入れて|外して|切り替え/,
  /作っ|作成|作って|つくって|新規/,
  /書き換え|書いて|追記|足して|加えて/,
  /消し|削除|けして/,
  /実装|対応して|やって|進めて|続けて/,
  /動かし|走らせ|実行|起動|ビルド|テストして/,
  /調べて|探して|見て|確認して|読んで/,
  /リファクタ|整理して|分けて|まとめて/,
  /commit|push|pull|merge|refactor|implement|fix|add|remove|run|build|test/i,
];

/**
 * 問いかけだと**はっきり分かる**形。
 *
 * 作業の合図が無いだけでは足りない。「echo を使って」は作業の動詞に
 * 当てはまらなかったので問いとして扱われ、ツールを取り上げてしまった
 * （自分の試験が先に落とした）。**合図が在るものだけを通す。**
 */
const ASKS_A_QUESTION = [
  /[？?]\s*$/, // 明日の天気は？
  /^(こんにちは|こんばんは|おはよう|ありがとう|どうも|よろしく|はじめまして)/,
  /教えて|知ってる|知ってますか|どう思う|とは何|とは\?|って何|ってなに|何ですか/,
  /^[\d\s+\-*/().=^%]+$/, // 1+1=
];

/** これより長いものは、問いかけとして扱わない。 */
const CHAT_MAX_CHARS = 80;

/**
 * 問いかけ・雑談として扱ってよいか。
 *
 * true なら、作業者の決まりもツールも載せずに、素直に答えさせる。
 */
export function looksLikeChat(text: string): boolean {
  const t = text.trim();
  if (!t) return false;
  // 長いものは、作業の説明であることが多い。安全側（作業）へ倒す。
  if (t.length > CHAT_MAX_CHARS) return false;
  if (POINTS_AT_CODE.some((re) => re.test(t))) return false;
  if (ASKS_FOR_WORK.some((re) => re.test(t))) return false;
  // ここまでで「作業の合図が無い短い文」。**問いの合図が在るものだけ**を通す。
  return ASKS_A_QUESTION.some((re) => re.test(t));
}
