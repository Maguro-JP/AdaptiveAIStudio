/**
 * 覚えの一行にする。覚え直したものと同じ形に揃える。
 * **必ず場面から書く。**場面の無い戒めは、次に手を変える助けにならない。
 */
export function lessonLine(l: BuiltinLesson): string {
  return `【場面】${l.when} / 【したこと】${l.did} — ${l.why} / 【次から】${l.next}`;
}
