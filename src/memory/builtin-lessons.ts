/**
 * 最初から持っている「二度としないこと」。
 *
 * ここに在るのは、この場所の利用者が実際に指摘してきたこと。
 * **入れた直後の何も知らない状態から、同じ地雷を踏み直させない。**
 *
 * 一つずつ、次の三つで書く。原文は置かない（記録であって学びではないため）。
 *
 *   何が悪いか / なぜ相手が困るか / 次からどうするか
 *
 * 覚え直したものと同じ形にしてあるので、思い出し方も刈られ方も同じ
 * （話題が違っても出る。刈らない）。
 */

export interface BuiltinLesson {
  /** 短い見出し。同じことを覚え直したときに重ねるための鍵にもなる。 */
  title: string;
  /**
   * どういう場面だったか。**これが無いと学びにならない。**
   *
   * 場面を落とすと「提案したら怒られた」「黙っていたら怒られた」が並ぶだけになり、
   * 何をしても怒られる＝**相手が理不尽だ、という記録**にしかならない。
   * 次に同じ場面が来たときに手を変えられるよう、条件のほうを書く。
   */
  when: string;
  /** その場面で、こちらが何をしたか。 */
  did: string;
  why: string;
  next: string;
}

